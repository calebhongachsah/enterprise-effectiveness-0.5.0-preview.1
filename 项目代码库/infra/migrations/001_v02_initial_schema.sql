BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value_json jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS process_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_no integer NOT NULL UNIQUE CHECK (version_no > 0),
  status text NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
  config_json jsonb NOT NULL,
  baselines_json jsonb,
  change_note text NOT NULL,
  created_at timestamptz NOT NULL,
  published_at timestamptz
);

CREATE TABLE IF NOT EXISTS import_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename text NOT NULL,
  imported_at timestamptz NOT NULL,
  as_of timestamptz NOT NULL,
  total_rows integer NOT NULL CHECK (total_rows >= 0),
  valid_rows integer NOT NULL CHECK (valid_rows >= 0),
  error_rows integer NOT NULL CHECK (error_rows >= 0),
  status text NOT NULL DEFAULT 'PUBLISHED' CHECK (
    status IN ('READY_TO_PUBLISH', 'READY_WITH_ERRORS', 'PUBLISHED', 'REJECTED')
  ),
  config_json jsonb,
  new_rows integer NOT NULL DEFAULT 0 CHECK (new_rows >= 0),
  updated_rows integer NOT NULL DEFAULT 0 CHECK (updated_rows >= 0),
  unchanged_rows integer NOT NULL DEFAULT 0 CHECK (unchanged_rows >= 0),
  published_at timestamptz,
  config_version_id bigint REFERENCES process_versions(id)
);

CREATE TABLE IF NOT EXISTS import_issues (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id bigint NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
  row_number integer NOT NULL CHECK (row_number > 0),
  ticket_id text,
  code text NOT NULL,
  message text NOT NULL
);

CREATE TABLE IF NOT EXISTS import_batch_records (
  batch_id bigint NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
  ticket_id text NOT NULL,
  classification text NOT NULL CHECK (classification IN ('new', 'updated', 'unchanged')),
  source_json jsonb NOT NULL,
  measurements_json jsonb NOT NULL,
  PRIMARY KEY (batch_id, ticket_id)
);

CREATE TABLE IF NOT EXISTS work_items (
  ticket_id text PRIMARY KEY,
  title text NOT NULL,
  team text NOT NULL,
  priority text NOT NULL,
  current_status text NOT NULL,
  release_result text,
  source_json jsonb NOT NULL,
  batch_id bigint NOT NULL REFERENCES import_batches(id)
);

CREATE TABLE IF NOT EXISTS stage_observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text NOT NULL REFERENCES work_items(ticket_id) ON DELETE CASCADE,
  stage_id text NOT NULL,
  stage_name text NOT NULL,
  stage_type text NOT NULL,
  priority text NOT NULL,
  started_at timestamptz,
  ended_at timestamptz,
  state text NOT NULL,
  hours double precision,
  sla_hours double precision NOT NULL CHECK (sla_hours >= 0),
  overdue boolean
);

CREATE TABLE IF NOT EXISTS problems (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  stage_id text NOT NULL,
  impact text NOT NULL,
  owner text NOT NULL,
  status text NOT NULL DEFAULT '新建',
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS problem_work_items (
  problem_id bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
  ticket_id text NOT NULL REFERENCES work_items(ticket_id) ON DELETE CASCADE,
  PRIMARY KEY (problem_id, ticket_id)
);

CREATE TABLE IF NOT EXISTS reasons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
  ticket_id text REFERENCES work_items(ticket_id) ON DELETE SET NULL,
  category text NOT NULL,
  detail text NOT NULL,
  author text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS actions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
  content text NOT NULL,
  owner text NOT NULL,
  due_date date,
  status text NOT NULL DEFAULT '计划中',
  expected_change text NOT NULL
);

CREATE TABLE IF NOT EXISTS verifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id bigint NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
  baseline_window text NOT NULL,
  after_window text NOT NULL,
  metric text NOT NULL,
  guardrail text NOT NULL,
  conclusion text NOT NULL,
  notes text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS operational_reasons (
  ticket_id text NOT NULL REFERENCES work_items(ticket_id) ON DELETE CASCADE,
  stage_id text NOT NULL,
  kind text NOT NULL,
  category text NOT NULL,
  detail text NOT NULL,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (ticket_id, stage_id, kind)
);

INSERT INTO schema_migrations(version)
VALUES ('001_v02_initial_schema')
ON CONFLICT (version) DO NOTHING;

COMMIT;
