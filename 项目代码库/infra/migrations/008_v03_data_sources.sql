BEGIN;

CREATE TABLE IF NOT EXISTS data_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  process_id text NOT NULL DEFAULT 'default',
  name text NOT NULL,
  connector_type text NOT NULL CHECK (connector_type IN ('POSTGRESQL')),
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'DISABLED')),
  host text NOT NULL,
  port integer NOT NULL DEFAULT 5432 CHECK (port BETWEEN 1 AND 65535),
  database_name text NOT NULL,
  username text NOT NULL,
  ssl_mode text NOT NULL DEFAULT 'VERIFY_FULL' CHECK (ssl_mode IN ('VERIFY_FULL', 'REQUIRE', 'DISABLE')),
  source_schema text,
  source_object text,
  source_object_kind text CHECK (source_object_kind IN ('TABLE', 'VIEW')),
  business_key_field text,
  updated_at_field text,
  mapping_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  schedule_json jsonb NOT NULL DEFAULT '{"enabled":false,"frequency":"DAILY","hour":2,"minute":0}'::jsonb,
  mapping_version integer NOT NULL DEFAULT 1 CHECK (mapping_version > 0),
  last_schema_fingerprint text,
  created_by bigint REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (process_id, name),
  CHECK (
    status <> 'ACTIVE' OR (
      source_schema IS NOT NULL AND source_object IS NOT NULL AND
      source_object_kind IS NOT NULL AND business_key_field IS NOT NULL AND
      updated_at_field IS NOT NULL AND mapping_json <> '{}'::jsonb
    )
  )
);

CREATE TABLE IF NOT EXISTS data_source_secrets (
  data_source_id bigint PRIMARY KEY REFERENCES data_sources(id) ON DELETE CASCADE,
  encrypted_value bytea NOT NULL,
  initialization_vector bytea NOT NULL,
  authentication_tag bytea NOT NULL,
  key_version integer NOT NULL DEFAULT 1 CHECK (key_version > 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS data_source_mapping_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_source_id bigint NOT NULL REFERENCES data_sources(id) ON DELETE CASCADE,
  version_no integer NOT NULL CHECK (version_no > 0),
  mapping_json jsonb NOT NULL,
  source_schema_json jsonb NOT NULL,
  schema_fingerprint text NOT NULL,
  created_by bigint REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz,
  UNIQUE (data_source_id, version_no)
);

CREATE TABLE IF NOT EXISTS sync_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_source_id bigint NOT NULL REFERENCES data_sources(id),
  mapping_version_id bigint REFERENCES data_source_mapping_versions(id),
  run_type text NOT NULL CHECK (run_type IN ('FULL', 'INCREMENTAL')),
  trigger_type text NOT NULL CHECK (trigger_type IN ('MANUAL', 'SCHEDULED', 'RETRY')),
  status text NOT NULL CHECK (status IN (
    'QUEUED', 'CONNECTING', 'EXTRACTING', 'VALIDATING', 'READY_TO_PUBLISH',
    'PUBLISHING', 'PUBLISHED', 'FAILED', 'QUALITY_BLOCKED', 'SCHEMA_BLOCKED', 'CANCELLED'
  )),
  started_at timestamptz,
  finished_at timestamptz,
  cursor_start_json jsonb,
  cursor_end_json jsonb,
  rows_read integer NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
  rows_new integer NOT NULL DEFAULT 0 CHECK (rows_new >= 0),
  rows_updated integer NOT NULL DEFAULT 0 CHECK (rows_updated >= 0),
  rows_unchanged integer NOT NULL DEFAULT 0 CHECK (rows_unchanged >= 0),
  rows_rejected integer NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
  error_code text,
  error_summary text,
  attempt_no integer NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_data_sources_status ON data_sources(status);
CREATE INDEX IF NOT EXISTS idx_sync_runs_source_created ON sync_runs(data_source_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sync_runs_one_active_per_source
  ON sync_runs(data_source_id)
  WHERE status IN ('QUEUED', 'CONNECTING', 'EXTRACTING', 'VALIDATING', 'READY_TO_PUBLISH', 'PUBLISHING');

INSERT INTO schema_migrations(version)
VALUES ('008_v03_data_sources')
ON CONFLICT (version) DO NOTHING;

COMMIT;
