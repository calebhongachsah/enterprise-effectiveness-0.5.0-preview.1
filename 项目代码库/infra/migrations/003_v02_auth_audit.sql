BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  display_name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('SYSTEM_ADMIN', 'OPERATIONS_LEAD', 'TEAM_LEAD', 'EXECUTOR', 'VIEWER')),
  active boolean NOT NULL DEFAULT true,
  must_change_password boolean NOT NULL DEFAULT false,
  failed_login_count integer NOT NULL DEFAULT 0,
  locked_until timestamptz,
  password_changed_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_team_scopes (
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  team text NOT NULL,
  PRIMARY KEY (user_id, team)
);

CREATE TABLE IF NOT EXISTS sessions (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  source_ip text,
  user_agent text
);

CREATE TABLE IF NOT EXISTS audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  session_id uuid,
  source_ip text,
  action text NOT NULL,
  object_type text NOT NULL,
  object_id text,
  result text NOT NULL CHECK (result IN ('SUCCESS', 'DENIED', 'FAILED')),
  details_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_sessions_token_active
  ON sessions(token_hash, expires_at) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_audit_events_occurred
  ON audit_events(occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_user
  ON audit_events(user_id, occurred_at DESC);

INSERT INTO schema_migrations(version)
VALUES ('003_v02_auth_audit')
ON CONFLICT (version) DO NOTHING;

COMMIT;
